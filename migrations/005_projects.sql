-- Project storage and sync between a person's devices (Keel Make).
-- A project is metadata plus records (threads, messages, the model, context,
-- outputs, exports). Large or binary content (the model package, photos,
-- datasheets, STEP files, thumbnails, exports) lives in blobs, addressed by
-- sha256 per account. Every write takes the next number of the account's
-- change sequence, so a device asks for "everything after N".

create table sync_cursors (
  account_id  uuid primary key references accounts(id) on delete cascade,
  seq         bigint not null default 0
);

create table projects (
  id           uuid primary key,                 -- generated by the app
  account_id   uuid not null references accounts(id) on delete cascade,
  revision     integer not null default 1,
  seq          bigint not null,
  name         text not null default '',
  data         jsonb not null default '{}'::jsonb,
  blob_sha256  text,                             -- thumbnail, optional
  device_id    uuid,                             -- device that made the last change
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);
create index projects_account_seq_idx on projects(account_id, seq);

create table project_records (
  project_id   uuid not null references projects(id) on delete cascade,
  collection   text not null,
  id           text not null,
  account_id   uuid not null references accounts(id) on delete cascade,
  revision     integer not null default 1,
  seq          bigint not null,
  data         jsonb,
  blob_sha256  text,
  device_id    uuid,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz,
  primary key (project_id, collection, id)
);
create index project_records_account_seq_idx on project_records(account_id, seq);
create index project_records_project_seq_idx on project_records(project_id, seq);
create index project_records_blob_idx on project_records(account_id, blob_sha256) where blob_sha256 is not null;

create table blobs (
  account_id    uuid not null references accounts(id) on delete cascade,
  sha256        text not null,
  size          bigint not null,
  content_type  text not null,
  storage_key   text not null,
  created_at    timestamptz not null default now(),
  primary key (account_id, sha256)
);

-- Bytes for the Postgres blob store (development, tests, or a deploy without
-- an S3 bucket). Production uses an S3-compatible bucket and leaves this empty.
create table blob_chunks (
  storage_key  text not null,
  idx          integer not null,
  data         bytea not null,
  primary key (storage_key, idx)
);
