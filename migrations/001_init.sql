-- Keel account service, phase 1 schema.
-- Money is always stored as integer micro dollars (1 USD = 1,000,000).

create extension if not exists pgcrypto;

create table accounts (
  id             uuid primary key default gen_random_uuid(),
  apple_user_id  text not null unique,
  email_relay    text,
  plan           text not null default 'beta',
  status         text not null default 'active' check (status in ('active', 'suspended', 'deleted')),
  created_at     timestamptz not null default now()
);

create table devices (
  id                uuid primary key,             -- generated by the app, stable per install
  account_id        uuid not null references accounts(id) on delete cascade,
  name              text,
  app_version       text,
  app_attest_key_id text,                         -- phase 2
  push_token        text,                         -- phase 3
  created_at        timestamptz not null default now(),
  last_seen_at      timestamptz not null default now(),
  revoked_at        timestamptz
);
create index devices_account_idx on devices(account_id);

create table refresh_tokens (
  id           uuid primary key default gen_random_uuid(),
  token_hash   bytea not null unique,             -- sha256 of the token; the token itself is never stored
  device_id    uuid not null references devices(id) on delete cascade,
  account_id   uuid not null references accounts(id) on delete cascade,
  created_at   timestamptz not null default now(),
  expires_at   timestamptz not null,
  revoked_at   timestamptz,
  replaced_by  uuid references refresh_tokens(id)
);
create index refresh_tokens_device_idx on refresh_tokens(device_id);

create table usage_ledger (
  id                  bigserial primary key,
  account_id          uuid not null references accounts(id) on delete cascade,
  device_id           uuid references devices(id) on delete set null,
  project_hash        text not null,              -- HMAC of the app's opaque project id
  thread_id           text not null,
  run_id              text not null,
  turn_index          integer not null,
  task_type           text not null,
  kind                text not null default 'turn' check (kind in ('turn', 'keepwarm', 'batch')),
  model               text not null,
  served_model        text,                       -- set when a server-side fallback served the turn
  input_tokens        integer not null default 0,
  cache_write_tokens  integer not null default 0,
  cache_read_tokens   integer not null default 0,
  output_tokens       integer not null default 0,
  cost_micros         bigint not null default 0,
  stop_reason         text,
  latency_ms          integer not null default 0,
  config_version      integer,
  created_at          timestamptz not null default now()
);
create index usage_ledger_account_time_idx on usage_ledger(account_id, created_at);
create index usage_ledger_run_idx on usage_ledger(account_id, run_id);

-- Running total per account per calendar month (UTC), updated in the same
-- transaction as each ledger row so allowance checks are one indexed read.
create table allowances (
  account_id    uuid not null references accounts(id) on delete cascade,
  month         date not null,                    -- first day of the month, UTC
  limit_micros  bigint not null,
  used_micros   bigint not null default 0,
  primary key (account_id, month)
);

create table config_versions (
  version     serial primary key,
  doc         jsonb not null,
  author      text not null,
  note        text,
  created_at  timestamptz not null default now()
);
